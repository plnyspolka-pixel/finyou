-- ── Odblokowanie wniosków do ponownego scoringu ──────────────────────────────
-- NEEDS_DATA/FAILED są terminalne (tick ich nie podnosi), PROCESSING może
-- zostać po przerwanym ticku. Wszystkie z numerem KW wracają do kolejki.
UPDATE public.loan_applications la
  SET location_scoring_status = 'PENDING'
  WHERE la.location_scoring_status IN ('NEEDS_DATA', 'FAILED', 'PROCESSING')
    AND EXISTS (
      SELECT 1 FROM public.properties p
      WHERE p.loan_application_id = la.id
        AND p.land_register_number IS NOT NULL
        AND btrim(p.land_register_number) <> ''
    );
