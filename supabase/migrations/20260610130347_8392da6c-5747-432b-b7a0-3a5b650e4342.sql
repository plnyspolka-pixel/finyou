Pożyczkę pod zastaw mieszkania można dziś wziąć dwoma drogami: w **banku** (kredyt hipoteczny lub konsolidacyjny zabezpieczony hipoteką) albo u **prywatnego pożyczkodawcy** (pozabankowa pożyczka hipoteczna). Każdy z tych kanałów ma zupełnie inną strukturę kosztów. Jeżeli porównujesz oferty „na pierwszy rzut oka", łatwo wyciągnąć błędne wnioski — bo bank pokazuje jedną liczbę (RRSO), a pożyczka prywatna drugą (np. miesięczne oprocentowanie i prowizję). Poniżej rozkładamy obie opcje na czynniki pierwsze.

## Koszty pożyczki bankowej pod zastaw mieszkania

Bank zarabia głównie na **odsetkach rozłożonych w długim czasie** (10–30 lat) i na opłatach okołokredytowych. Procedura jest długa (4–10 tygodni), ale jednostkowy koszt miesięczny — niski.

### 1. Oprocentowanie: WIBOR/WIRON + marża
Podstawa oprocentowania w polskim banku to wskaźnik rynku międzybankowego (**WIBOR 3M/6M** lub w nowych umowach **WIRON**) plus **marża banku** (zwykle 1,8–2,8 p.p.). Przykładowo: WIBOR 3M ~5,8% + marża 2,1% = oprocentowanie roczne ok. 7,9%. To wartość *zmienna* — gdy RPP tnie stopy, raty spadają (i odwrotnie). Alternatywą jest **okresowo stałe oprocentowanie** na 5–10 lat (przewidywalność, ale zwykle 0,2–0,5 p.p. drożej na starcie).

### 2. Prowizja za udzielenie kredytu
Najczęściej **0–3% kwoty kredytu**, doliczana jednorazowo. Część banków oferuje „0% prowizji" w zamian za wyższą marżę albo obowiązkowe ubezpieczenia.

### 3. Operat szacunkowy (wycena nieruchomości)
Bank wymaga **operatu szacunkowego rzeczoznawcy majątkowego**. Koszt: **600–1500 zł** za mieszkanie, **1200–2500 zł** za dom. Płatne z góry, nawet jeśli kredyt finalnie nie zostanie udzielony.

### 4. Ubezpieczenia
- **Ubezpieczenie nieruchomości** od ognia i zdarzeń losowych — obowiązkowe przez cały okres kredytu (cesja na bank). Roczna składka: zwykle 200–600 zł.
- **Ubezpieczenie na życie** — formalnie dobrowolne, faktycznie wymuszane niższą marżą; 30–80 zł miesięcznie.
- **Ubezpieczenie pomostowe** — do czasu wpisu hipoteki (zwykle 2–4 miesiące). Podwyższa marżę o ~1 p.p. w tym okresie.

### 5. Koszty sądowe i notarialne
- Wpis hipoteki do księgi wieczystej: **200 zł** + PCC **19 zł**.
- Akt notarialny ustanowienia hipoteki (przy kredytach konsumpcyjnych zabezpieczonych hipoteką): taksa notarialna wg widełek, zwykle 1500–4000 zł przy nieruchomości wartej 500 tys. zł.

**Sumarycznie** — w banku zapłacisz na starcie ok. **2,5–5 tys. zł kosztów wstępnych** plus odsetki rozłożone na lata. RRSO bankowych kredytów hipotecznych w 2026 r. mieści się zwykle w przedziale **8–11%**.

## Koszty pożyczki prywatnej pod zastaw mieszkania

Pożyczka prywatna (pozabankowa) to inny świat. Decyzja zapada w **24–72 godziny**, dokumentacja jest minimalna, akceptowalna jest zła historia BIK i brak zdolności bankowej, akceptowane są też nieruchomości problematyczne (II hipoteka, działka, lokal użytkowy, zadłużona spółdzielnia). Za to koszt jest **prostszy w konstrukcji, ale wyższy procentowo**, bo pożyczkodawca bierze na siebie znacznie większe ryzyko.

### 1. Oprocentowanie
Najczęściej **maksymalne odsetki ustawowe** = 2 × (stopa referencyjna NBP + 3,5 p.p.). Przy obecnej stopie NBP ~5,75% daje to limit ok. **18,5% rocznie**. To górna granica — żaden uczciwy podmiot nie zejdzie znacząco niżej, bo poniżej tego pułapu kalkulacja ryzyka przestaje się spinać.

### 2. Prowizja
Pobierana **jednorazowo z kwoty pożyczki** przy wypłacie. Typowo **5–15%** kwoty. Mieści się w ustawowym limicie pozaodsetkowych kosztów kredytu (art. 36a UKK dla pożyczek konsumenckich; przy pożyczkach na cele firmowe limit nie obowiązuje, ale rzetelni pożyczkodawcy i tak go respektują).

### 3. Co **nie** wchodzi w koszt pożyczki prywatnej
W przeciwieństwie do banku, w dobrze poukładanej pożyczce prywatnej **nie ma**:
- operatu szacunkowego — wystarczy zdjęcia, KW i własna analiza pożyczkodawcy,
- ubezpieczenia na życie ani pomostowego,
- wymogu wykupu dodatkowych produktów (konto, karta, polisa inwestycyjna).

Dochodzą jedynie **koszty notarialne** (akt ustanowienia hipoteki — zwykle 1–3 tys. zł zależnie od wartości nieruchomości) i **opłata sądowa za wpis hipoteki** (200 zł + 19 zł PCC). Te same w banku i poza nim.

