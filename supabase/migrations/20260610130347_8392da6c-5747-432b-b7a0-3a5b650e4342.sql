## FAQ

**Czy w pożyczce prywatnej muszę mieć operat szacunkowy?**
Nie. Wartość nieruchomości szacujemy na podstawie księgi wieczystej, zdjęć, lokalizacji i porównania z aktualnymi transakcjami w okolicy. Klient nic z tego tytułu nie płaci.

**Czy mogę spłacić pożyczkę prywatną wcześniej?**
Tak. Zgodnie z prawem konsumenckim masz prawo do wcześniejszej spłaty z proporcjonalnym zwrotem prowizji za niewykorzystany okres. W praktyce większość naszych klientów refinansuje pożyczkę w banku po 12–18 miesiącach.

**Co składa się na RRSO pożyczki prywatnej?**
RRSO obejmuje oprocentowanie + prowizję + koszty notarialne i sądowe, rozliczone w skali roku z uwzględnieniem harmonogramu spłat. Przy 18% oprocentowania i 8% prowizji na 24 miesiące RRSO wyniesie zwykle 27–31%.

